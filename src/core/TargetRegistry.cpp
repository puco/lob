constexpr auto kCommandOption = QLatin1String("--command=");
constexpr auto kUserDataDirOption = QLatin1String("--user-data-dir=");
constexpr auto kConfigHomeAssignment = QLatin1String("XDG_CONFIG_HOME=");

// Desktop ids that are never real routing destinations: PWA/web-app stubs
// generated by browsers, and rival link routers (including any older build of
// ourselves) which would bounce the URL straight back.
const QStringList kSkipIdPrefixes = {
    QStringLiteral("ffpwa-"),
    QStringLiteral("userapp-"),
    QStringLiteral("firefoxpwa"),
    QStringLiteral("browser_integration"),
    QStringLiteral("browsertamer"),
    QStringLiteral("junction"),
    QStringLiteral("app.lane.Lane"),
};

QStringList execTokens(const QString &exec)
{
    KShell::Errors error = KShell::NoError;
    const QStringList args = KShell::splitArgs(exec, KShell::AbortOnMeta, &error);
    if (error != KShell::NoError || args.isEmpty()) {
        return {};
    }
    return args;
}

QString resolveExecPath(const QString &token)
{
    if (token.isEmpty()) {
        return {};
    }
    const QString found = token.contains(QLatin1Char('/')) ? token : QStandardPaths::findExecutable(token);
    if (found.isEmpty()) {
        return {};
    }
    return QFileInfo(found).absoluteFilePath();
}

/// Lowercased blob of every identifying field. StartupWMClass is often the most
/// stable of them, so it is worth folding in alongside the exec name.
QString fingerprint(const KService::Ptr &service, const QString &execBasename)
{
    const QString wmClass = service->property<QString>(QStringLiteral("StartupWMClass"));
    return (execBasename + QLatin1Char(' ') + service->name() + QLatin1Char(' ') + service->desktopEntryName()
            + QLatin1Char(' ') + wmClass)
        .toLower();
}

EngineFamily guessFamily(const QString &print)
{
    static const QStringList gecko = {
        QStringLiteral("firefox"),
        QStringLiteral("librewolf"),
        QStringLiteral("waterfox"),
        QStringLiteral("floorp"),
        QStringLiteral("zen"),
        QStringLiteral("mullvad-browser"),
        QStringLiteral("icecat"),
    };
    static const QStringList chromium = {
        QStringLiteral("chrome"),
        QStringLiteral("chromium"),
        QStringLiteral("edge"),
        QStringLiteral("brave"),
        QStringLiteral("vivaldi"),
        QStringLiteral("opera"),
        QStringLiteral("thorium"),
    };

    for (const QString &needle : gecko) {
        if (print.contains(needle)) {
            return EngineFamily::Gecko;
        }
    }
    for (const QString &needle : chromium) {
        if (print.contains(needle)) {
            return EngineFamily::Chromium;
        }
    }
    return EngineFamily::Unknown;
}

/// Flags that mean "private window" in some browser. Not exhaustive by
/// construction -- it is a hint for reading an action, not the only way in.
const QStringList kKnownPrivateFlags = {
    QStringLiteral("--private-window"),   QStringLiteral("-private-window"),
    QStringLiteral("--private"),          QStringLiteral("-private"),
    QStringLiteral("--private-browsing"), QStringLiteral("--incognito"),
    QStringLiteral("--inprivate"),
};

/// Arguments a private-window action may carry that say nothing about privacy.
const QStringList kNotPrivateFlags = {
    QStringLiteral("--new-window"), QStringLiteral("--new-tab"),
    QStringLiteral("--"),           QStringLiteral("--file-forwarding"),
};

/// The flag in a command line that turns it into a private window, if any.
/// Known spellings win; otherwise the first option the entry passes to the
/// application itself is it, which is how forks nobody has heard of still work.
QString privateFlagIn(const QStringList &command)
{
    const int application = Launcher::programIndex(command);
    if (application < 0) {
        return {};
    }
    for (const QString &arg : command) {
        if (kKnownPrivateFlags.contains(arg)) {
            return arg;
        }
    }
    for (int n = application + 1; n < command.size(); ++n) {
        const QString arg = command.at(n);
        if (arg.startsWith(QLatin1Char('-')) && !arg.contains(QLatin1Char('='))
            && !kNotPrivateFlags.contains(arg)) {
            return arg;
        }
    }
    return {};
}

/// Reads the private-window flag out of the entry's own desktop action. Matched
/// on the action id, never the display text -- Edge's reads "New InPrivate
/// Window" and Chrome's "New Incognito Window", and both are translated. Entries
/// that spell the id differently are still caught by the second pass, which
/// accepts only a flag we recognise.
QString privateFlagFor(const KService::Ptr &service, EngineFamily family, const QString &print, QStringList *privateCommand)
{
    const auto actions = service->actions();
    for (bool byName : {true, false}) {
        for (const KServiceAction &action : actions) {
            if (byName != (action.name() == QLatin1String("new-private-window"))) {
                continue;
            }
            const auto args = execTokens(action.exec());
            if (!Launcher::commandIsSafe(args)) {
                continue;
            }
            const QString flag = privateFlagIn(args);
            if (flag.isEmpty() || (!byName && !kKnownPrivateFlags.contains(flag))) {
                continue;
            }
            *privateCommand = args;
            return flag;
        }
    }

    switch (family) {
    case EngineFamily::Gecko:
        return QStringLiteral("--private-window");
    case EngineFamily::Chromium:
        return print.contains(QLatin1String("edge")) ? QStringLiteral("--inprivate") : QStringLiteral("--incognito");
    case EngineFamily::Unknown:
        return {};
    }
    return {};
}

QString findDataDir(const QString &execBasename, const QString &storageId, EngineFamily family, const QString &flatpakId,
                    const QString &configHome, const QString &explicitDataDir)
{
    if (!explicitDataDir.isEmpty()) { return explicitDataDir; }
    const QString sandbox = QDir::homePath() + QStringLiteral("/.var/app/") + flatpakId + QLatin1Char('/');
    const auto scoped = [&](QStringList candidates) {
        if (!flatpakId.isEmpty()) {
            candidates.removeIf([&](const QString &path) { return !path.startsWith(sandbox); });
        } else {
            candidates.removeIf([](const QString &path) { return path.contains(QLatin1String("/.var/app/")); });
            if (!configHome.isEmpty()) {
                const QString normal = QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation);
                for (auto &path : candidates) {
                    if (path.startsWith(normal + QLatin1Char('/'))) { path.replace(0, normal.size(), configHome); }
                }
            }
        }
        return candidates;
    };
    if (family == EngineFamily::Gecko) {
        const auto candidates = scoped(geckoDataDirCandidates(execBasename, storageId));
        for (const QString &dir : candidates) {
            if (isGeckoDataDir(dir)) {
                return dir;
            }
        }
    } else if (family == EngineFamily::Chromium) {
        const auto candidates = scoped(chromiumDataDirCandidates(execBasename, storageId));
        for (const QString &dir : candidates) {
            if (isChromiumDataDir(dir)) {
                return dir;
            }
        }
    }
    return {};
}

/// A known engine is proof enough. Failing that, we trust the entry's own
/// declaration: Categories=WebBrowser is how a browser announces itself, and it
/// is what separates a real browser from an app like chatgpt.desktop that
/// registers for https only to catch OAuth callbacks.
bool isBrowser(const KService::Ptr &service, EngineFamily family)
{
    if (family != EngineFamily::Unknown) {
        return true;
    }
    return service->categories().contains(QLatin1String("WebBrowser"), Qt::CaseInsensitive);
}

bool shouldSkip(const KService::Ptr &service, const QString &ownStorageId)
{
    if (service->storageId() == ownStorageId) {
        return true;
    }
    const QString entryName = service->desktopEntryName();
    for (const QString &prefix : kSkipIdPrefixes) {
        if (entryName.startsWith(prefix, Qt::CaseInsensitive)) {
            return true;
        }
    }
    return false;
}

