Target TargetRegistry::resolve(const QList<Target> &targets, const QString &id, bool remembered)
{
    if (remembered && !id.contains(QLatin1Char('#'))) {
        QList<Target> profiles;
        for (const auto &target : targets) {
            if (target.storageId == id && !target.profileKey.isEmpty()) { profiles.append(target); }
        }
        if (profiles.size() > 1) { return {}; } // a legacy memory cannot identify which profile was intended
        if (profiles.size() == 1) { return profiles.first(); }
    }
    for (const auto &target : targets) {
        if (target.id == id) { return target; }
    }
    return {};
}

QList<Target> TargetRegistry::withoutRedundantProfiles(const QList<Target> &targets)
{
    // The browser's own entry opens whichever profile that browser defaults to,
    // so it and that profile are two names for the same click. Which of the two
    // to leave out depends on which name says more:
    //
    //   - one profile: the browser's name is the better label, so the profile
    //     row goes ("Firefox", not "Firefox — default").
    //   - several: the explicit rows say which profile they open and the bare
    //     row does not, so the bare row goes.
    //   - several, none of them marked default: nothing is dropped, because
    //     which profile the bare row would open is genuinely unknown.
    //
    // Both ids stay resolvable throughout. This decides what is listed, never
    // what a rule or a memory can name.
    struct Browser {
        int profiles = 0;
        bool hasOwnEntry = false;
        bool knowsDefaultProfile = false;
    };

    QHash<QString, Browser> browsers;
    for (const auto &target : targets) {
        Browser &browser = browsers[target.storageId];
        if (target.profileKey.isEmpty()) {
            browser.hasOwnEntry = true;
            continue;
        }
        ++browser.profiles;
        browser.knowsDefaultProfile = browser.knowsDefaultProfile || target.isDefaultProfile;
    }

    QList<Target> listed;
    listed.reserve(targets.size());
    std::copy_if(targets.cbegin(), targets.cend(), std::back_inserter(listed), [&browsers](const Target &target) {
        const Browser browser = browsers.value(target.storageId);
        if (!browser.hasOwnEntry || browser.profiles == 0) {
            return true;
        }
        return target.profileKey.isEmpty() ? browser.profiles == 1 || !browser.knowsDefaultProfile
                                           : browser.profiles > 1;
    });
    return listed;
}

QList<Target> TargetRegistry::discover(const QString &ownStorageId)
{
    const KService::List services = KApplicationTrader::queryByMimeType(
        QStringLiteral("x-scheme-handler/https"),
        [&ownStorageId](const KService::Ptr &service) {
            // queryByMimeType applies no filtering of its own beyond this
            // lambda -- NoDisplay in particular is ours to handle, and on Arch
            // it is exactly what distinguishes microsoft-edge.desktop from its
            // com.microsoft.Edge.desktop twin.
            if (service->noDisplay()) {
                return false;
            }
            if (service->exec().isEmpty()) {
                return false;
            }
            return !shouldSkip(service, ownStorageId);
        });

    return fromServices(services, ownStorageId);
}

QList<Target> TargetRegistry::fromServices(const KService::List &services, const QString &ownStorageId)
{
    QList<Target> targets;

    for (const KService::Ptr &service : services) {
        if (!service || service->noDisplay() || shouldSkip(service, ownStorageId)) { continue; }
        auto command = execTokens(service->exec());
        if (!Launcher::commandIsSafe(command)) { continue; }
        const QString execToken = command.first();
        const QString execPath = resolveExecPath(execToken);
        if (execPath.isEmpty()) {
            continue;
        }

        command[0] = execPath;
        const int program = Launcher::programIndex(command);
        QString configHome;
        for (int n = 1; n < program; ++n) {
            // An entry that relocates the config home relocates the profiles
            // with it, so the scanner has to be told where to look.
            if (command.at(n).startsWith(kConfigHomeAssignment)) {
                configHome = command.at(n).mid(kConfigHomeAssignment.size());
            }
        }
        QString execBasename = QFileInfo(command.value(program)).fileName();
        const QString storageId = service->storageId();
        QString flatpakId;
        int applicationIndex = program;
        if (execBasename == QLatin1String("flatpak")) {
            flatpakId = service->property<QString>(QStringLiteral("X-Flatpak"));
            const QStringList optionsWithValue = {QStringLiteral("--command"), QStringLiteral("--arch"),
                QStringLiteral("--branch"), QStringLiteral("--env"), QStringLiteral("--unset-env"),
                QStringLiteral("--filesystem"), QStringLiteral("--device"), QStringLiteral("--socket"),
                QStringLiteral("--nosocket"), QStringLiteral("--persist"), QStringLiteral("--talk-name"),
                QStringLiteral("--own-name"), QStringLiteral("--system-talk-name"), QStringLiteral("--cwd")};
            for (int n = program + 2; n < command.size(); ++n) {
                if (command.at(n) == QLatin1String("--")) { ++n; applicationIndex = n; break; }
                if (optionsWithValue.contains(command.at(n))) { ++n; continue; }
                if (command.at(n).startsWith(QLatin1Char('-'))) { continue; }
                applicationIndex = n;
                break;
            }
            if (flatpakId.isEmpty()) {
                const auto ref = command.value(applicationIndex);
                flatpakId = ref.startsWith(QLatin1String("app/")) ? ref.section(QLatin1Char('/'), 1, 1)
                                                                               : ref.section(QLatin1Char('/'), 0, 0);
            }
            execBasename.clear();
            for (int n = program + 2; n < applicationIndex; ++n) {
                const auto arg = command.at(n);
                if (arg.startsWith(kCommandOption)) { execBasename = QFileInfo(arg.mid(kCommandOption.size())).fileName(); }
                if (arg == QLatin1String("--command")) { execBasename = QFileInfo(command.value(n + 1)).fileName(); }
            }
            if (execBasename.isEmpty()) {
                static const QMap<QString, QString> flatpakExecutables = {
                    {QStringLiteral("org.mozilla.firefox"), QStringLiteral("firefox")},
                    {QStringLiteral("org.chromium.Chromium"), QStringLiteral("chromium")},
                    {QStringLiteral("com.google.Chrome"), QStringLiteral("google-chrome")},
                    {QStringLiteral("com.microsoft.Edge"), QStringLiteral("microsoft-edge")},
                    {QStringLiteral("com.brave.Browser"), QStringLiteral("brave")},
                    {QStringLiteral("io.gitlab.librewolf-community"), QStringLiteral("librewolf")},
                };
                execBasename = flatpakExecutables.value(flatpakId);
            }
        }
        QString explicitDataDir;
        for (int n = program + 1; n < command.size(); ++n) {
            const auto arg = command.at(n);
            if (arg.startsWith(kUserDataDirOption)) { explicitDataDir = arg.mid(kUserDataDirOption.size()); }
            if (arg == QLatin1String("--user-data-dir")) { explicitDataDir = command.value(n + 1); }
        }

        // Fingerprint decides the engine, which decides the launch flags. The
        // profile store is a separate question: finding it unlocks per-profile
        // targets, but not finding it must not demote a real browser. Firefox
        // that has never been launched has no ~/.mozilla yet and is still a
        // browser -- on this machine it is the current default one.
        const QString print = fingerprint(service, execBasename);
        const EngineFamily family = guessFamily(print);
        const QString dataDir = findDataDir(execBasename, flatpakId.isEmpty() ? storageId : flatpakId + QStringLiteral(".desktop"),
                                            family, flatpakId, configHome, explicitDataDir);

        Target base;
        base.storageId = storageId;
        base.execPath = execPath;
        base.command = command;
        base.applicationName = service->name();
        base.desktopFilePath = service->entryPath();
        base.flatpakId = flatpakId;
        base.browserExecutable = execBasename;
        base.workingDirectory = service->workingDirectory();
        base.terminal = service->terminal();
        base.terminalOptions = service->terminalOptions();
        base.applicationIndex = applicationIndex;
        base.iconName = service->icon();
        base.label = service->name();
        base.family = family;
        base.dataDir = dataDir;
        base.kind = isBrowser(service, family) ? TargetKind::Browser : TargetKind::OtherHandler;
        base.privateFlag = privateFlagFor(service, family, print, &base.privateCommand);
        base.id = storageId;

        QList<ProfileInfo> profiles;
        if (!dataDir.isEmpty() && family == EngineFamily::Gecko) {
            profiles = scanGeckoProfiles(dataDir);
        } else if (!dataDir.isEmpty() && family == EngineFamily::Chromium) {
            profiles = scanChromiumProfiles(dataDir);
        }

        // The bare entry is the browser's own default profile, and stays
        // routable: a rule may deliberately mean "whatever Firefox opens with".
        // Every profile gets its own identity regardless of how many there are
        // today, so an id written down now still means the same thing after a
        // second profile appears. withoutRedundantProfiles() is what keeps the
        // picker from showing one browser twice.
        targets.append(base);

        for (const ProfileInfo &profile : std::as_const(profiles)) {
            Target target = base;
            target.profileKey = profile.key;
            target.profileName = profile.name;
            target.isDefaultProfile = profile.isDefault;
            target.id = storageId + QLatin1Char('#') + profile.key;
            target.label = base.label + QStringLiteral(" — ") + profile.name;
            targets.append(target);
        }
    }

    // Browsers first; other handlers are opt-in and sort below them.
    //
    // Within each group the order is alphabetical rather than whatever
    // KApplicationTrader returned: that is sorted by mimeapps preference and
    // shifts as associations change, which would silently reassign the picker's
    // digit shortcuts between one link and the next. A shortcut you cannot
    // trust is worse than no shortcut.
    std::sort(targets.begin(), targets.end(), [](const Target &a, const Target &b) {
        const bool aBrowser = a.kind == TargetKind::Browser;
        const bool bBrowser = b.kind == TargetKind::Browser;
        if (aBrowser != bBrowser) {
            return aBrowser;
        }
        const int byLabel = a.label.localeAwareCompare(b.label);
        return byLabel != 0 ? byLabel < 0 : a.id < b.id;
    });

    return targets;
}

